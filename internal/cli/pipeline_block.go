package cli

import (
	"errors"
	"io"
	"strconv"

	"github.com/richardrh/valet/internal/app"
	"go.yaml.in/yaml/v3"
)

// writePipelineBlock prints the planned schema as an input section to paste
// into a pipeline. Nodes rather than string formatting keep any column name
// correctly quoted.
func writePipelineBlock(w io.Writer, plan *app.PlanDescription) error {
	if plan == nil {
		return errors.New("cannot present a nil plan")
	}
	columns := &yaml.Node{Kind: yaml.MappingNode}
	for _, field := range plan.Schema {
		spec := &yaml.Node{Kind: yaml.MappingNode, Style: yaml.FlowStyle}
		addField(spec, "type", scalar(field.Type, "!!str"))
		if field.Precision > 0 {
			addField(spec, "precision", scalar(strconv.Itoa(int(field.Precision)), "!!int"))
			addField(spec, "scale", scalar(strconv.Itoa(int(field.Scale)), "!!int"))
		}
		if field.Timezone != "" {
			addField(spec, "timezone", scalar(field.Timezone, "!!str"))
		}
		if !field.Nullable {
			addField(spec, "nullable", scalar("false", "!!bool"))
		}
		addField(columns, field.Name, spec)
	}
	schema := &yaml.Node{Kind: yaml.MappingNode}
	addField(schema, "extra_fields", scalar("error", "!!str"))
	addField(schema, "columns", columns)
	input := &yaml.Node{Kind: yaml.MappingNode}
	addField(input, "type", scalar(plan.Format, "!!str"))
	addField(input, "schema", schema)
	root := &yaml.Node{Kind: yaml.MappingNode, HeadComment: "Generated by valet plan. Review the types, then add rules."}
	addField(root, "input", input)
	encoder := yaml.NewEncoder(w)
	encoder.SetIndent(2)
	if err := encoder.Encode(&yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{root}}); err != nil {
		return err
	}
	return encoder.Close()
}

func addField(mapping *yaml.Node, key string, value *yaml.Node) {
	mapping.Content = append(mapping.Content, scalar(key, "!!str"), value)
}

func scalar(value, tag string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: tag, Value: value}
}
